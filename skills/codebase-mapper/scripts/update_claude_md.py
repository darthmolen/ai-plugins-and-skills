#!/usr/bin/env python3
"""
CLAUDE.md Updater

Writes the combined codebase map to its own file (documentation/CODEBASE-MAP.md
by default) and puts a short pointer to it in CLAUDE.md, between markers.
CLAUDE.md is loaded into every session; the map is only read when needed.
Preserves hand-written sections outside the markers.

Usage:
    python update_claude_md.py --claude-md ./CLAUDE.md --maps /tmp/map_python.md /tmp/map_csharp.md
    python update_claude_md.py --claude-md ./CLAUDE.md --maps /tmp/map_*.md --map-file ./docs/MAP.md
    python update_claude_md.py --claude-md ./CLAUDE.md --remove
"""

import argparse
import subprocess
import sys
from pathlib import Path
from datetime import datetime


START_MARKER = "<!-- CODEBASE-MAP:AUTO-START -->"
END_MARKER = "<!-- CODEBASE-MAP:AUTO-END -->"

DEFAULT_INSERT_AFTER = "## Project Context"

MAP_FILENAME = "CODEBASE-MAP.md"
DOCS_DIR_CANDIDATES = ("documentation", "docs")


def read_maps(map_files: list[Path]) -> str:
    """Read and combine map files."""
    sections = []

    for map_file in map_files:
        if not map_file.exists():
            print(f"Warning: Map file not found: {map_file}", file=sys.stderr)
            continue

        content = map_file.read_text(encoding='utf-8').strip()
        if content:
            sections.append(content)

    return "\n\n".join(sections)


def resolve_map_path(repo_root: Path, override: Path | None = None) -> Path:
    """Pick where the map file lives: override, else an existing docs folder, else documentation/."""
    if override is not None:
        return override

    for name in DOCS_DIR_CANDIDATES:
        if (repo_root / name).is_dir():
            return repo_root / name / MAP_FILENAME

    return repo_root / DOCS_DIR_CANDIDATES[0] / MAP_FILENAME


def git_short_sha(repo_root: Path) -> str | None:
    """Short HEAD SHA, or None outside a git repository."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=repo_root, capture_output=True, text=True, check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return result.stdout.strip() or None


def write_map_file(map_path: Path, map_content: str, repo_root: Path) -> None:
    """Write the map with a header saying when, and from which commit, it was built."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    sha = git_short_sha(repo_root)
    built_from = f" from commit `{sha}`" if sha else ""
    header = (
        "# Codebase Map\n\n"
        f"*Auto-generated by codebase-mapper on {timestamp}{built_from}. "
        "Re-run the skill to refresh. If this disagrees with the code, the code wins.*\n"
    )

    map_path.parent.mkdir(parents=True, exist_ok=True)
    map_path.write_text(header + "\n" + map_content + "\n", encoding='utf-8')


def build_pointer(rel_path: str) -> str:
    """The CLAUDE.md section that points at the map file.

    The path is written in backticks, never as an "@path" import: CLAUDE.md
    imports are inlined at load time, which would put the whole map back into
    every session.
    """
    return (
        "## Architecture Map\n\n"
        f"Before searching for where a class, module, or file lives, read `{rel_path}`\n"
        "(generated by codebase-mapper; its header shows the commit it was built from).\n"
        "If it disagrees with the code, trust the code and use Grep/Glob."
    )


def relative_posix(path: Path, root: Path) -> str:
    """Path relative to root with forward slashes, or absolute if outside root."""
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def update_claude_md(claude_md_path: Path, section_content: str, insert_after: str) -> bool:
    """Update CLAUDE.md with section content using markers."""

    if not claude_md_path.exists():
        print(f"Error: CLAUDE.md not found: {claude_md_path}", file=sys.stderr)
        return False

    content = claude_md_path.read_text(encoding='utf-8')

    # Build the marked section
    marked_section = f"\n\n{START_MARKER}\n{section_content}\n{END_MARKER}\n"

    # Check if markers already exist
    start_idx = content.find(START_MARKER)
    end_idx = content.find(END_MARKER)

    if start_idx != -1 and end_idx != -1:
        # Replace content between markers
        new_content = (
            content[:start_idx] +
            START_MARKER + "\n" +
            section_content + "\n" +
            content[end_idx:]
        )
        print(f"Updated existing map section in {claude_md_path}")
    else:
        # Insert after specified section
        insert_pos = content.find(insert_after)
        if insert_pos == -1:
            # Insert at end if section not found
            new_content = content.rstrip() + marked_section
            print(f"Appended map section to end of {claude_md_path}")
        else:
            # Find end of the section (next ## or end of file)
            section_end = content.find("\n## ", insert_pos + len(insert_after))
            if section_end == -1:
                section_end = len(content)

            new_content = (
                content[:section_end].rstrip() +
                marked_section +
                content[section_end:]
            )
            print(f"Inserted map section after '{insert_after}' in {claude_md_path}")

    # Write updated content
    claude_md_path.write_text(new_content, encoding='utf-8')
    return True


def remove_map_section(claude_md_path: Path, map_path: Path) -> bool:
    """Remove the map section from CLAUDE.md and delete the map file."""
    if not claude_md_path.exists():
        print(f"Error: CLAUDE.md not found: {claude_md_path}", file=sys.stderr)
        return False

    if map_path.exists():
        map_path.unlink()
        print(f"Deleted {map_path}")

    content = claude_md_path.read_text(encoding='utf-8')

    start_idx = content.find(START_MARKER)
    end_idx = content.find(END_MARKER)

    if start_idx == -1 or end_idx == -1:
        print("No map section found to remove")
        return True

    # Remove the section including surrounding whitespace
    before = content[:start_idx].rstrip()
    after = content[end_idx + len(END_MARKER):].lstrip()

    new_content = before + "\n\n" + after

    claude_md_path.write_text(new_content, encoding='utf-8')
    print(f"Removed map section from {claude_md_path}")
    return True


def count_tokens_estimate(text: str) -> int:
    """Rough estimate of token count (words * 1.3)."""
    words = len(text.split())
    return int(words * 1.3)


def main(argv: list[str] | None = None):
    parser = argparse.ArgumentParser(description='Write the codebase map file and point at it from CLAUDE.md')
    parser.add_argument('--claude-md', type=Path, required=True,
                        help='Path to CLAUDE.md (its directory is treated as the repo root)')
    parser.add_argument('--maps', type=Path, nargs='*',
                        help='Map files to merge')
    parser.add_argument('--map-file', type=Path, default=None,
                        help=f'Where to write the map (default: documentation/ or docs/{MAP_FILENAME})')
    parser.add_argument('--insert-after', type=str, default=DEFAULT_INSERT_AFTER,
                        help=f'Section header to insert after (default: "{DEFAULT_INSERT_AFTER}")')
    parser.add_argument('--remove', action='store_true',
                        help='Remove the pointer section and the map file instead of updating')
    parser.add_argument('--dry-run', action='store_true',
                        help='Show what would be done without making changes')
    args = parser.parse_args(argv)

    repo_root = args.claude_md.parent
    map_path = resolve_map_path(repo_root, args.map_file)

    if args.remove:
        if args.dry_run:
            print(f"Would remove map section from {args.claude_md} and delete {map_path}")
        else:
            remove_map_section(args.claude_md, map_path)
        return

    if not args.maps:
        print("Error: No map files specified", file=sys.stderr)
        sys.exit(1)

    # Handle glob patterns (shell expansion)
    map_files = []
    for pattern in args.maps:
        if '*' in str(pattern):
            map_files.extend(pattern.parent.glob(pattern.name))
        else:
            map_files.append(pattern)

    map_content = read_maps(map_files)

    if not map_content:
        print("Error: No map content to insert", file=sys.stderr)
        sys.exit(1)

    pointer = build_pointer(relative_posix(map_path, repo_root))
    pointer_tokens = count_tokens_estimate(pointer)
    map_tokens = count_tokens_estimate(map_content)

    if args.dry_run:
        print(f"Would write map to {map_path} (~{map_tokens} tokens, read on demand)")
        print(f"Would update {args.claude_md} (~{pointer_tokens} tokens, loaded every session)")
        print(f"Insert after: '{args.insert_after}'")
        print(f"\n--- Pointer ---\n")
        print(START_MARKER)
        print(pointer)
        print(END_MARKER)
        return

    if not args.claude_md.exists():
        print(f"Error: CLAUDE.md not found: {args.claude_md}", file=sys.stderr)
        sys.exit(1)

    write_map_file(map_path, map_content, repo_root)
    print(f"Wrote map to {map_path}")

    success = update_claude_md(args.claude_md, pointer, args.insert_after)
    if not success:
        sys.exit(1)

    print(f"\nSuccess! Map: ~{map_tokens} tokens in {map_path} (read on demand).")
    print(f"CLAUDE.md pointer: ~{pointer_tokens} tokens (loaded every session).")
    print(f"Re-run this script anytime to refresh the map.")


if __name__ == '__main__':
    main()
